--GROUP BY bei CATEGORY

SELECT CATEGORY1, CATEGORY2, CATEGORY3, CATEGORY4,
SUM(TOTALPRICE) AS TORALPRICE, --Parasal Olarak Kaç Satır
COUNT (*) AS ROWCOUNT_, 
SUM (AMOUNT) AS TOTALAMOUNT --Adet Olarak Kaç Satır

FROM SALES
GROUP BY  CATEGORY1, CATEGORY2, CATEGORY3, CATEGORY4
ORDER BY  CATEGORY1, CATEGORY2, CATEGORY3, CATEGORY4
